import { GROUPS, PROMPT_DOCS, TOOL_DOCS, type Effect } from "./tool-docs.js";

/**
 * Builds the reference for the MCP tools and prompts from the live server (what exists, and each parameter) and the
 * plain-language entries in tool-docs.ts. Pure: the generator script and the tests both call it.
 */

interface Schema { type?: string; description?: string; enum?: unknown[]; items?: Schema; properties?: Record<string, Schema>; required?: string[] }
export interface LiveTool { name: string; description?: string; inputSchema: Schema; annotations?: { readOnlyHint?: boolean } }
export interface LivePrompt { name: string; description?: string; arguments?: { name: string; description?: string; required?: boolean }[] }

export interface ReferenceParam { name: string; type: string; required: boolean; description: string }
export interface ReferenceTool {
  name: string; summary: string; when: string; effect: Effect;
  /** The tool asks for the writer's go-ahead (a `writer_approved` parameter), so Claude can't call it before you agree. */
  needsApproval: boolean;
  params: ReferenceParam[];
}
export interface Reference {
  version: string;
  groups: { name: string; tools: ReferenceTool[] }[];
  prompts: { name: string; command: string; summary: string; how: string; args: { name: string; required: boolean; description: string }[] }[];
}

/** A parameter's type in words. Lists and objects name their fields (optional ones end in ?), so the reference isn't empty for them. */
function typeOf(s: Schema, depth = 0): string {
  if (s.enum) return `one of ${s.enum.map((v) => `"${String(v)}"`).join(", ")}`;
  if (s.type === "array") return `list of ${s.items ? typeOf(s.items, depth + 1) : "values"}`;
  if (s.type === "object" || s.properties) {
    const req = new Set(s.required ?? []);
    const fields = Object.entries(s.properties ?? {});
    if (!fields.length) return "object";
    if (depth >= 3) return "object";
    return `{ ${fields.map(([k, p]) => `${k}${req.has(k) ? "" : "?"}: ${typeOf(p, depth + 1)}`).join(", ")} }`;
  }
  if (s.type === "integer") return "whole number";
  return s.type ?? "value";
}

export function buildReference(tools: LiveTool[], prompts: LivePrompt[], version: string): Reference {
  const known = new Set(Object.keys(TOOL_DOCS));
  const missing = tools.filter((t) => !known.has(t.name)).map((t) => t.name);
  if (missing.length) throw new Error(`No entry in src/tool-docs.ts for: ${missing.join(", ")}`);
  const gone = [...known].filter((n) => !tools.some((t) => t.name === n));
  if (gone.length) throw new Error(`src/tool-docs.ts documents tools that no longer exist: ${gone.join(", ")}`);
  const missingPrompts = prompts.filter((p) => !PROMPT_DOCS[p.name]).map((p) => p.name);
  if (missingPrompts.length) throw new Error(`No prompt entry in src/tool-docs.ts for: ${missingPrompts.join(", ")}`);

  const byName = new Map(tools.map((t) => [t.name, t]));
  const groups = GROUPS.map((name) => ({
    name: name as string,
    tools: Object.entries(TOOL_DOCS).filter(([, d]) => d.group === name).map(([toolName, d]): ReferenceTool => {
      const schema = byName.get(toolName)!.inputSchema;
      const required = new Set(schema.required ?? []);
      const props = Object.entries(schema.properties ?? {});
      return {
        name: toolName, summary: d.summary, when: d.when, effect: d.effect,
        needsApproval: props.some(([k]) => k === "writer_approved"),
        params: props.filter(([k]) => k !== "writer_approved").map(([k, p]) => ({ name: k, type: typeOf(p), required: required.has(k), description: p.description ?? "" })),
      };
    }),
  }));
  const stray = Object.values(TOOL_DOCS).filter((d) => !(GROUPS as readonly string[]).includes(d.group));
  if (stray.length) throw new Error(`A tool entry uses a group that is not in GROUPS: ${stray.map((d) => d.group).join(", ")}`);

  return {
    version,
    groups,
    prompts: prompts.map((p) => ({
      name: p.name, command: PROMPT_DOCS[p.name].command, summary: PROMPT_DOCS[p.name].summary, how: PROMPT_DOCS[p.name].how,
      args: (p.arguments ?? []).map((a) => ({ name: a.name, required: a.required === true, description: a.description ?? "" })),
    })),
  };
}

const EFFECT_TEXT: Record<Effect, string> = {
  reads: "Only reads. Changes nothing.",
  saves: "Saves data you can still edit in Writ.",
  creates: "Creates something new.",
  "moves the piece on": "Ends a step and moves the piece on.",
};

export function toMarkdown(ref: Reference): string {
  const out: string[] = [
    "# Writ in Claude: what each tool does",
    "",
    `Version ${ref.version}. **Generated** from the MCP server by \`npm run docs:update\`: do not edit this file. To change a description, edit \`src/tool-docs.ts\`.`,
    "",
    "Writ's tools let Claude read your pieces and save work into Writ, on your own Claude subscription. You approve every step that changes the piece's direction; what Claude saves stays editable in Writ. While you are editing the outline or a section in Writ, Claude's saves to it are refused with a message until you finish, so you never overwrite each other.",
    "",
  ];
  for (const g of ref.groups) {
    out.push(`## ${g.name}`, "");
    for (const t of g.tools) {
      out.push(`### \`${t.name}\``, "", t.summary, "", `- **Used:** ${t.when}`, `- **Effect:** ${EFFECT_TEXT[t.effect]}${t.needsApproval ? " Needs your go-ahead first." : ""}`);
      if (t.params.length) {
        out.push("", "| Parameter | Type | Required | What it is |", "|---|---|---|---|");
        for (const p of t.params) out.push(`| \`${p.name}\` | ${p.type.replace(/\|/g, "\\|")} | ${p.required ? "yes" : "no"} | ${p.description.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\n/g, " ")} |`);
      }
      out.push("");
    }
  }
  out.push("## Prompts", "", "Start these from Claude by typing the command.", "");
  for (const p of ref.prompts) {
    out.push(`### \`${p.command}\``, "", p.summary, "", p.how);
    if (p.args.length) out.push("", ...p.args.map((a) => `- \`${a.name}\`${a.required ? "" : " (optional)"}: ${a.description}`));
    out.push("");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

/** The same reference as a TypeScript module, for the page in the Writ app. */
export function toAppModule(ref: Reference): string {
  return `// GENERATED by scripts/export-tool-docs.mjs in writ-mcp-server (npm run docs:update). Do not edit here:
// change src/tool-docs.ts in the MCP server, then run the script again.

export interface McpParam { name: string; type: string; required: boolean; description: string }
export interface McpTool {
  name: string;
  summary: string;
  when: string;
  effect: "reads" | "saves" | "creates" | "moves the piece on";
  needsApproval: boolean;
  params: McpParam[];
}
export interface McpPrompt { name: string; command: string; summary: string; how: string; args: { name: string; required: boolean; description: string }[] }
export interface McpReference { version: string; groups: { name: string; tools: McpTool[] }[]; prompts: McpPrompt[] }

export const MCP_REFERENCE: McpReference = ${JSON.stringify(ref, null, 2)};
`;
}
