// Regenerates src/format-presets.ts from the Writ web app, so the MCP server adds the same standard formats the app offers.
//
//   node scripts/export-format-presets.mjs        (the app repo is the parent folder; or pass its path)
//
// It bundles the app's own web/src/lib/sections.ts (FORMAT_TEMPLATES) and web/src/lib/recipes.ts (presetFor, validate),
// then gives EVERY format the full blog workflow (the "longform_blog" recipe, with every step switched on): scope with its
// AI thread, research with web search and the SERP landscape, the gap analysis, the outline with its AI thread and SEO/GEO
// check, section research and briefs, writing, and the grammar, fact, contract, SEO and GEO checks. The writer decides
// which steps to follow in each piece. Only what makes a format that format is kept from its own preset: its name and
// description, its brief fields (a case study's customer, a promotion's offer), a fixed outline's sections, the customer
// approval check, and its sign-off settings. Each recipe is checked with the app's own validate() and the script stops
// if any has problems.
//
// Run it again whenever presetFor or FORMAT_TEMPLATES changes in the app.

import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import os from "node:os";

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const appRoot = process.argv[2] ?? process.env.WRIT_APP_DIR ?? path.join(here, "..", "..");
if (!fs.existsSync(path.join(appRoot, "web"))) {
  console.error("Usage: node scripts/export-format-presets.mjs <path to the Writ app repo>");
  process.exit(1);
}
const web = path.join(appRoot, "web");
const require = createRequire(path.join(web, "package.json"));
const esbuild = require("esbuild");

const entry = `
export { FORMAT_TEMPLATES } from ${JSON.stringify(path.join(web, "src/lib/sections.ts").replace(/\\/g, "/"))};
export { presetFor, validate } from ${JSON.stringify(path.join(web, "src/lib/recipes.ts").replace(/\\/g, "/"))};
`;
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "writ-presets-"));
const out = path.join(tmp, "bundle.mjs");
await esbuild.build({ stdin: { contents: entry, resolveDir: web, loader: "ts" }, bundle: true, format: "esm", platform: "node", outfile: out, logLevel: "error" });
const { FORMAT_TEMPLATES, presetFor, validate } = await import(pathToFileURL(out).href);

const blog = presetFor("longform_blog");

/** The blog workflow with every step on, keeping only what makes the format itself (see the header comment). */
const fullBlogWorkflow = (key) => {
  const own = presetFor(key);
  const r = JSON.parse(JSON.stringify(blog));
  // The base only labels the workflow. Every format has the long-form workflow, except the case study, which keeps its own.
  r.base = own.base === "case_study" ? "case_study" : blog.base;
  r.brief.customer = own.brief.customer;
  r.brief.offer = own.brief.offer;
  if (own.outline.mode === "fixed") {
    r.outline.mode = "fixed";
    r.outline.template = own.outline.template;
    // The app's own rule (validate): outline suggestions need a free outline, so a fixed outline cannot have them.
    r.outline.ai_thread = false;
  }
  r.checks.customer_approval = own.checks.customer_approval;
  r.signoff = JSON.parse(JSON.stringify(own.signoff));
  return r;
};

const templates = FORMAT_TEMPLATES.map((t) => {
  const recipe = fullBlogWorkflow(t.key);
  const issues = validate(recipe);
  if (issues.length) {
    console.error(`Preset ${t.key} has problems with the full blog workflow:`, issues);
    process.exit(1);
  }
  return { key: t.key, name: t.name, description: t.description, recipe };
});

const body = `// GENERATED by scripts/export-format-presets.mjs from the Writ web app. Do not edit by hand: run the script again.
// Every preset has the full blog workflow with every step switched on. Only the format's own shape is kept from its preset
// (brief fields, a fixed outline's sections, the customer approval check, sign-off settings).

export interface FormatPreset {
  key: string;
  name: string;
  description: string;
  recipe: Record<string, unknown>;
}

export const FORMAT_PRESETS: FormatPreset[] = ${JSON.stringify(templates, null, 2)};
`;
const dest = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..", "src", "format-presets.ts");
fs.writeFileSync(dest, body);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`Wrote ${templates.length} presets to ${dest}`);
const fixed = templates.filter((t) => t.recipe.outline.mode === "fixed").map((t) => t.key);
console.log("Full blog workflow applied to every format. Fixed outlines kept for:", fixed.join(", ") || "none");
